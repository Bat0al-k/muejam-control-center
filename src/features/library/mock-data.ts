export function getEditorialReviewById(id: string): BookEditorialReview {
  const found = INITIAL_EDITORIAL_REVIEWS.find(
    (item) => item.id.toLowerCase() === id.toLowerCase()
  );
  if (found) return found;

  // Check matching pending books
  const pending = INITIAL_PENDING_BOOKS.find(
    (item) => item.id.toLowerCase() === id.toLowerCase()
  );
  if (pending) {
    return {
      id: pending.id,
      bookTitle: pending.title,
      bookSubtitle: pending.coverSubtitle || "Editorial Manuscript",
      edition: "1st Ed",
      category: pending.category,
      version: "v1.0.0",
      status: "Pending Review",
      submittedBy: pending.author,
      submittedDate: pending.timeAgo,
      editorialQueue: "Technical Archival Tier 1",
      isbn: pending.isbn || "978-1-95432-019-2",
      pageCount: pending.pages,
      wordCount: `${Math.round(pending.pages * 290 / 1000)}k`,
      chapterCount: Math.round(pending.pages / 9),
      assetArchiveSize: pending.fileSize,
      coverTheme: pending.coverTheme,
      author: {
        name: pending.author,
        degree: "Research Fellow, Editorial Contributor",
        email: "author@nexus-research.io",
        avatarInitials: pending.author.split(" ").map((w) => w[0]).join("").slice(0, 2),
        avatarBg: "bg-slate-200 text-slate-800",
        verified: true,
        booksCount: 5,
        avgRating: 4.85,
        tier: "Tier 1 Author",
      },
      chapters: INITIAL_EDITORIAL_REVIEWS[0].chapters,
      flaggedIssues: ["Code Licensing"],
      revisionDirectives: INITIAL_EDITORIAL_REVIEWS[0].revisionDirectives,
    };
  }

  // Check submissions
  const sub = INITIAL_SUBMISSIONS.find(
    (item) => item.id.toLowerCase() === id.toLowerCase()
  );
  if (sub) {
    const pageNum = parseInt(sub.pages, 10) || 320;
    return {
      id: sub.id,
      bookTitle: sub.title,
      bookSubtitle: "Ingested Editorial Manuscript",
      edition: "1st Ed",
      category: sub.category || "General Library",
      version: "v1.0.0",
      status: sub.status,
      submittedBy: sub.authorName,
      submittedDate: sub.submittedDate,
      editorialQueue: "Editorial Archival Queue",
      isbn: sub.isbn,
      pageCount: pageNum,
      wordCount: `${Math.round(pageNum * 280 / 1000)}k`,
      chapterCount: Math.round(pageNum / 10),
      assetArchiveSize: sub.fileSize || "14.2 MB",
      coverTheme: sub.coverTheme === "draft" ? "light" : sub.coverTheme,
      author: {
        name: sub.authorName,
        degree: "Verified Contributor",
        email: sub.authorEmail,
        avatarInitials: sub.authorInitials,
        avatarBg: sub.authorAvatarBg,
        verified: true,
        booksCount: 3,
        avgRating: 4.8,
        tier: "Tier 2 Author",
      },
      chapters: INITIAL_EDITORIAL_REVIEWS[0].chapters,
      flaggedIssues: ["Format & Layout"],
      revisionDirectives: "Editorial notes and revision guidance for manuscript layout.",
    };
  }

  // Default to the exact book from screenshot
  return INITIAL_EDITORIAL_REVIEWS[0];
}
