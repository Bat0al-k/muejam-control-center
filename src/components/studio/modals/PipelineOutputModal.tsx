"use client";

import React from "react";
import { ModalShell } from "./ModalShell";
import { useStudio } from "@/features/studio/context";
import { FiDownload, FiCheckCircle } from "react-icons/fi";

export function PipelineOutputModal() {
  const { activeModal, closeModal, activePipelines, showToast } = useStudio();

  const isOpen = activeModal?.type === "pipelineOutput";
  const pipelineId = isOpen ? activeModal.pipelineId : null;

  const pipeline = activePipelines.find((p) => p.id === pipelineId);

  const handleDownload = () => {
    showToast("success", "Downloading generative artifact...");
  };

  return (
    <ModalShell
      isOpen={isOpen}
      onClose={closeModal}
      title="Generative Output Artifact"
      subtitle={`Synthesized artifact for ${pipeline?.name || "Pipeline"} (${pipeline?.jobId})`}
      maxWidthClass="max-w-lg"
    >
      <div className="space-y-4">
        <div className="relative rounded-2xl overflow-hidden border border-[#E5E7EB] bg-[#0F172A] p-6 text-center text-white space-y-3">
          <div className="w-16 h-16 mx-auto rounded-full bg-emerald-500/20 text-emerald-400 flex items-center justify-center">
            <FiCheckCircle className="w-8 h-8" />
          </div>
          <div>
            <h4 className="text-base font-bold font-syne">Synthesis Complete</h4>
            <p className="text-xs text-slate-400 mt-1">
              {pipeline?.outputDescription || "Generative multi-modal output ready for deployment."}
            </p>
          </div>
          <div className="inline-block px-3 py-1 bg-white/10 rounded-full text-xs font-mono text-emerald-300">
            SHA256: 3c9b...882a (Integrity Verified)
          </div>
        </div>

        <div className="flex items-center justify-between text-xs text-[#6B7280]">
          <span>Generated by {pipeline?.user}</span>
          <span>Duration: {pipeline?.duration}</span>
        </div>

        <div className="flex items-center justify-end gap-3 pt-3 border-t border-[#F0F0F2]">
          <button
            type="button"
            onClick={closeModal}
            className="px-4 py-2 border border-[#D1D5DB] text-[#374151] rounded-xl text-xs font-semibold hover:bg-[#FAFAFB] transition-colors"
          >
            Close
          </button>
          <button
            type="button"
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-4 py-2 bg-[#E8785A] text-white rounded-xl text-xs font-semibold hover:bg-[#D96948] transition-colors shadow-sm"
          >
            <FiDownload className="w-3.5 h-3.5" />
            Download Artifact
          </button>
        </div>
      </div>
    </ModalShell>
  );
}
